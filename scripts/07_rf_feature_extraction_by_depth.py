"""
07_rf_feature_extraction.py

Random Forest feature extraction by soil depth.

This script must be run AFTER:
    scripts/06_ml_classification.py

Primary feature representation
------------------------------
Counts
    -> per-sample relative abundance
    -> log10(relative abundance + 1e-6)
    -> Random Forest

Purpose
-------
The fitted Random Forest model provides feature-importance values but does
not by itself indicate whether a predictive taxon is associated with the
upper or lower soil profile.

This script therefore:

1. Loads the fitted Random Forest pipeline.
2. Loads the exact feature names used during model fitting.
3. Recovers the exact training samples used by the fitted model.
4. Applies the preprocessing stored in the fitted pipeline.
5. Verifies that stored preprocessing matches LOG10_RA directly.
6. Extracts Random Forest feature importance.
7. Compares mean transformed abundance between Upper and Lower soil.
8. Assigns each feature a depth association.
9. Saves complete and top-ranked feature tables.
10. Generates the Random Forest feature-importance figure.

Repository structure
--------------------
Input:
    data/Allmerged_16Slevel-2.xlsx

Required model files:
    output/ml/log10_ra/
        best_random_forest_log10_ra.joblib
        rf_feature_names_log10_ra.csv
        rf_training_indices_log10_ra.csv

Tabular outputs:
    output/rf_features/
        RF_all_features_by_depth_log10_ra.csv
        RF_top_lower_soil_features_log10_ra.csv
        RF_top_upper_soil_features_log10_ra.csv
        RF_top_features_by_depth_log10_ra.csv

Figure outputs:
    figures/
        RF_top_features_by_depth_log10_ra.png
        RF_top_features_by_depth_log10_ra.pdf
"""


