# Imports
# =============================================================================

from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from matplotlib.patches import Patch


# =============================================================================
# 0) CONFIGURATION
# =============================================================================

NORMALIZATION = "LOG10_RA"


# -----------------------------------------------------------------------------
# Input phylum-level feature table
# -----------------------------------------------------------------------------

EXCEL_PATH = (
    Path("data")
    / "Allmerged_16Slevel-2.xlsx"
)


# -----------------------------------------------------------------------------
# Fitted-model outputs generated by 06_ml_classification.py
# -----------------------------------------------------------------------------

MODEL_DIR = (
    Path("output")
    / "ml"
    / "log10_ra"
)


# -----------------------------------------------------------------------------
# Tabular feature-extraction outputs
# -----------------------------------------------------------------------------

OUTPUT_DIR = (
    Path("output")
    / "rf_features"
)

OUTPUT_DIR.mkdir(
    parents=True,
    exist_ok=True
)


# -----------------------------------------------------------------------------
# Final manuscript figures
# -----------------------------------------------------------------------------

FIGURE_DIR = Path("figures")

FIGURE_DIR.mkdir(
    parents=True,
    exist_ok=True
)


# -----------------------------------------------------------------------------
# Number of leading features retained per soil-depth direction
# -----------------------------------------------------------------------------

TOP_N_PER_DEPTH = 10


print("=" * 78)

print(
    "RANDOM FOREST FEATURE EXTRACTION BY SOIL DEPTH"
)

print("=" * 78)


print(
    f"Normalization: {NORMALIZATION}"
)


print(
    f"Input table: {EXCEL_PATH}"
)


print(
    f"Model directory: {MODEL_DIR}"
)


